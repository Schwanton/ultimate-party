/** Gespiegelte Kopie einer Arena */
export function mirror(map: string[], h: boolean, v: boolean): string[] {
  let rows = map.slice();
  if (v) rows = rows.reverse();
  if (h) rows = rows.map((r) => r.split('').reverse().join(''));
  return rows;
}
