const platform: Record<Lang, Record<string, string>> = { de, en };

export function translate(lang: Lang, gameId: string | null, key: string, vars?: Record<string, string | number>): string {
  const game = gameId ? registry.find((g) => g.manifest.id === gameId) : undefined;
  let s = game?.i18n[lang]?.[key] ?? game?.i18n.en?.[key] ?? platform[lang][key] ?? platform.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useT(lang: Lang, gameId: string | null = null): Translate {
  return useMemo(() => (key, vars) => translate(lang, gameId, key, vars), [lang, gameId]);
}

export function guessLang(): Lang {
  try {
    const saved = localStorage.getItem('up:lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* egal */ }
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}
